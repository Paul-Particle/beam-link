"""Generate the atmospheric gaseous-absorption spectrum (ITU-R P.676) as a CSV.

itur is a heavy, generate-only dependency (astropy/scipy/pyproj), so it is NOT in
pyproject; run this with an ephemeral install:

    uv run --with itur python generate_spectrum.py

Output: data/atmospheric_attenuation.csv — specific attenuation γ (dB/km) vs
frequency for several atmospheric states. Rain is NOT stored here; it is computed
parametrically from napkin.rain_coefficients (ITU-R P.838) at plot time.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import astropy.units as u
from itur.models.itu676 import gamma_exact

# Surface pressure, water-vapour density, temperature per state.
# (name, pressure_hPa, water_vapour_gm3, temperature_K, note)
CONDITIONS = [
    ("dry_cold",       1013.0,  0.5, 273.0, "polar / winter — near-dry, oxygen only"),
    ("temperate",      1013.0,  7.5, 288.0, "ITU standard sea-level reference"),
    ("tropical_humid", 1013.0, 20.0, 300.0, "hot & humid — monsoon boundary layer"),
    ("cruise_11km",     226.0,  0.05, 217.0, "11 km: thin dry air (aircraft cruise)"),
    ("relay_20km",       55.0,  0.005, 217.0, "20 km: stratospheric relay — thinner still"),
]

# Dense grid: at 20 km the low pressure narrows the O2 lines until they resolve
# individually, so the 50-70 GHz complex needs fine sampling to render cleanly.
frequency_ghz = np.logspace(np.log10(1.0), np.log10(200.0), 2400)

frame = pd.DataFrame({"frequency_ghz": frequency_ghz})
notes = {}
for name, pressure_hpa, vapour_gm3, temperature_k, note in CONDITIONS:
    gamma_db_km = gamma_exact(
        frequency_ghz * u.GHz,
        pressure_hpa * u.hPa,
        vapour_gm3 * u.g / u.m ** 3,
        temperature_k * u.K,
    )
    frame[name] = np.asarray(gamma_db_km)
    notes[name] = note

out_dir = Path(__file__).parent / "data"
out_dir.mkdir(exist_ok=True)
out_path = out_dir / "atmospheric_attenuation.csv"

with out_path.open("w") as handle:
    handle.write("# ITU-R P.676 gaseous specific attenuation (dB/km) vs frequency (GHz).\n")
    handle.write("# Generated by generate_spectrum.py (uv run --with itur).\n")
    for name, _, _, _, note in CONDITIONS:
        handle.write(f"# {name}: {note}\n")
    frame.to_csv(handle, index=False)

print(f"wrote {out_path} ({len(frame)} rows, {len(CONDITIONS)} conditions)")
